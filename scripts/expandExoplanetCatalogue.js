// Stefan-Boltzmann radius calculation: R = sqrt(L / (T/5778)^4)
function _calcRadius(lum, temp) {
  const r = Math.sqrt(Math.max(1e-8, lum)) / Math.pow(temp / 5778, 2);
  return parseFloat(r.toFixed(3));
}

// Visual magnitude to luminosity approximation
function _magDistToLum(vMag, distPc) {
  const absMag = vMag - 5 * (Math.log10(distPc) - 1);
  const lum = Math.pow(10, (4.83 - absMag) / 2.5);
  return { absMag: parseFloat(absMag.toFixed(2)), lum: parseFloat(lum.toFixed(4)) };
}

