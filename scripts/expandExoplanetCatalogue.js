// Map existing stars in famous_stars to match exoplanet status
const existingNameMap = new Map();
famousStars.forEach(s => {
  existingNameMap.set(s.name.toLowerCase(), s);
  if (s.hip) existingNameMap.set(`hip_${s.hip}`, s);
});

let addedCount = 0;
let updatedCount = 0;

for (const host of curatedExoplanetHosts) {
  const byName = existingNameMap.get(host.name.toLowerCase());
  const byHip = host.hip ? existingNameMap.get(`hip_${host.hip}`) : null;
  const match = byName || byHip;

  if (match) {
    match.hasExoplanets = true;
    match.exoplanetCount = host.exoplanetCount;
    if (host.notableFacts) match.notableFacts = host.notableFacts;
    if (host.ra) match.ra = host.ra;
    if (host.dec) match.dec = host.dec;
    updatedCount++;
  } else {
    // Add new star
    const id = host.name.toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '');
    const newStar = {
      id,
      name: host.name,
      hip: host.hip,
      bayer: host.bayer,
      constellation: host.constellation,
      spectralType: host.spectralType,
      temp: host.temp,
      lum: host.lum,
      absMag: host.absMag,
      b_v: host.b_v,
      mass: host.mass,
      radius: host.radius,
      distance_ly: host.distance_ly,
      luminosityClass: host.luminosityClass,
      evolutionaryStage: host.evolutionaryStage,
      hasExoplanets: true,
      exoplanetCount: host.exoplanetCount,
      notableFacts: host.notableFacts,
      pulsationPeriodDays: null,
      ra: host.ra,
      dec: host.dec
    };
    famousStars.push(newStar);
    existingNameMap.set(host.name.toLowerCase(), newStar);
    if (host.hip) existingNameMap.set(`hip_${host.hip}`, newStar);
    addedCount++;
  }
}

// Also check and update existing stars like Vega, Proxima Centauri, TRAPPIST-1, etc.
famousStars.forEach(s => {
  const n = s.name.toLowerCase();
  if (n.includes('trappist-1')) { s.hasExoplanets = true; s.exoplanetCount = 7; }
  if (n.includes('kepler-186')) { s.hasExoplanets = true; s.exoplanetCount = 5; }
  if (n.includes('proxima')) { s.hasExoplanets = true; s.exoplanetCount = 3; }
  if (n.includes('pollux')) { s.hasExoplanets = true; s.exoplanetCount = 1; }
  if (n.includes('aldebaran')) { s.hasExoplanets = true; s.exoplanetCount = 1; }
  if (n.includes('barnard')) { s.hasExoplanets = true; s.exoplanetCount = 1; }
  if (n.includes('ross 128')) { s.hasExoplanets = true; s.exoplanetCount = 1; }
  if (n.includes('wolf 359')) { s.hasExoplanets = true; s.exoplanetCount = 2; }
  if (n.includes('sun') || n.includes('sol')) { s.hasExoplanets = true; s.exoplanetCount = 8; }
});

const finalExoCount = famousStars.filter(s => s.hasExoplanets).length;
console.log(`Updated ${updatedCount} existing stars with exoplanet telemetry.`);
console.log(`Added ${addedCount} new confirmed exoplanet systems.`);
console.log(`Total stars now: ${famousStars.length}, Stars with planets: ${finalExoCount}`);

