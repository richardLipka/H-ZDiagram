const fill = (template, val) => template.replace('{val}', val);

/** Approximate main-sequence lifetime t ≈ 10 Gyr (M/M☉)^−2.5, localized. */
export function formatLifetimeLocalized(massSolar, lang = 'en') {
  if (!massSolar || massSolar <= 0) return '—';
  const dict = translations[lang] || translations.en;
  const years = msLifetimeYears(massSolar);
  if (years >= 1e12) return fill(dict.lifetimeTrillion, formatSig(years / 1e12, lang, 2));
  if (years >= 1e9) return fill(dict.lifetimeBillion, formatSig(years / 1e9, lang, 2));
  return fill(dict.lifetimeMillion, formatSig(years / 1e6, lang, 2));
}

/** Age in years, localized. */
export function formatAgeLocalized(years, lang = 'en') {
  const dict = translations[lang] || translations.en;
  if (years >= 1e9) return fill(dict.ageBillion, formatSig(years / 1e9, lang, 3));
  if (years >= 1e6) return fill(dict.ageMillion, formatSig(years / 1e6, lang, 3));
  return fill(dict.ageYears, formatSig(years, lang, 3));
}

