/**
 * Teff and luminosity of a main-sequence star of the given mass, interpolated
 * in log M along the empirical sequence (0.075–59 M☉; clamped outside).
 */
export function mainSequenceParams(massSolar) {
  const seq = MAMAJEK_DWARF_SEQUENCE;
  const m = Math.max(seq[0][0], Math.min(seq[seq.length - 1][0], massSolar));
  let i = 0;
  while (i < seq.length - 2 && seq[i + 1][0] < m) i++;
  const [m0, t0, l0] = seq[i];
  const [m1, t1, l1] = seq[i + 1];
  const f = (Math.log10(m) - Math.log10(m0)) / (Math.log10(m1) - Math.log10(m0));
  const logT = Math.log10(t0) + f * (Math.log10(t1) - Math.log10(t0));
  const logL = l0 + f * (l1 - l0);
  return { temp: 10 ** logT, lum: 10 ** logL };
}
